#!/usr/bin/env node
/* Builds self-contained copies of the study pages into standalone/.
 *
 * The normal pages (NN-name/study.html, exam-drill/index.html, index.html) load the shared
 * assets/study.css + assets/study.js and each lecture's study-content.js, so they only
 * work inside the full repo folder. This script inlines all of that into single files:
 *
 *   standalone/index.html                      hub (links to the files next to it)
 *   standalone/NN-short-name.html              one per lecture, works on its own
 *   standalone/exam-drill.html                 all questions, works on its own
 *
 * Each file opens fine by itself after a download. Links between the pages only work
 * when the files sit in the same folder. Slide links point to GitHub.
 *
 * Run from the repo root:   node tools/build-standalone.js
 * Re-run after changing any study-content.js, assets/study.*, or index.html.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "standalone");
const REPO = "https://github.com/gijstimmer/Genomic-Architecture/blob/main";

const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const css = read("assets/study.css");
const studyJs = read("assets/study.js");
const FONTS = `<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,600;1,6..72,400&family=Figtree:wght@400;500;600&family=JetBrains+Mono:wght@400;500&display=swap">`;

// Inline scripts must not contain "</script" or the browser ends the tag early.
const safe = (js) => js.replace(/<\/script/gi, "<\\/script");
// Cross-links inside lecture content (../NN-name/study.html) become sibling files.
const relink = (s) => s.replace(/\.\.\/(\d\d-[\w-]+)\/study\.html/g, "$1.html");
const linksScript = (folder) => `<script>window.GA = { links: {
  hub: "index.html",
  drill: "exam-drill.html",
  slide: (lec, file) => ${JSON.stringify(`${REPO}/${folder}/slides/`)} + encodeURIComponent(file),
} };</script>`;

const page = (title, body) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
${FONTS}
<title>${title}</title>
<style>
${css}
</style>
</head>
<body>
<!-- Generated by tools/build-standalone.js. Do not edit; edit the source files and rebuild. -->
${body}
</body>
</html>
`;

const lectureDirs = fs.readdirSync(ROOT)
  .filter((d) => /^\d\d-/.test(d) && fs.existsSync(path.join(ROOT, d, "study-content.js")))
  .sort();

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT);
const write = (name, html) => { fs.writeFileSync(path.join(OUT, name), html); console.log("  standalone/" + name); };

// Lecture pages: take the lecture id from its study.html shell.
for (const dir of lectureDirs) {
  const shell = read(`${dir}/study.html`);
  const id = (shell.match(/GA\.lecturePage\("([^"]+)"\)/) || [])[1];
  const title = (shell.match(/<title>([^<]*)<\/title>/) || [])[1] || dir;
  if (!id) throw new Error(`${dir}/study.html: no GA.lecturePage("..") call found`);
  const content = relink(read(`${dir}/study-content.js`));
  write(`${dir}.html`, page(title, `<main class="wrap" id="app"></main>
${linksScript(dir)}
<script>
${safe(studyJs)}
</script>
<script>
${safe(content)}
</script>
<script>GA.lecturePage(${JSON.stringify(id)});</script>`));
}

// Exam drill: every lecture listed in exam-drill/index.html.
const drill = read("exam-drill/index.html");
const drillDirs = [...drill.matchAll(/<script src="\.\.\/([^/"]+)\/study-content\.js"><\/script>/g)].map((m) => m[1]);
write("exam-drill.html", page("Exam Drill", `<main class="wrap" id="app"></main>
${linksScript("")}
<script>
${safe(studyJs)}
</script>
${drillDirs.map((d) => `<script>\n${safe(relink(read(`${d}/study-content.js`)))}\n</script>`).join("\n")}
<script>GA.drillPage();</script>`));

// Hub: the root index.html with its links pointed at the sibling files.
let hub = read("index.html");
const swap = (from, to) => {
  if (!hub.includes(from)) throw new Error(`index.html: expected to find ${from}`);
  hub = hub.split(from).join(to);
};
swap(`<link rel="stylesheet" href="assets/study.css">`, `<style>\n${css}\n</style>`);
swap(`<script src="assets/study.js"></script>`, `<script>\n${safe(studyJs)}\n</script>`);
swap(`href="exam-drill/index.html"`, `href="exam-drill.html"`);
swap("`${dir}/study.html`", "`${dir}.html`");
swap("`${dir}/README.md`", `\`${REPO}/\${dir}\``);
write("index.html", hub.replace("<body>", "<body>\n<!-- Generated by tools/build-standalone.js. Do not edit; edit the source files and rebuild. -->"));

console.log(`Built ${lectureDirs.length} lecture pages + exam drill + hub into standalone/`);
